package com.senioradguard.risk

/**
 * 광고·연결 링크의 위험 등급.
 *
 * "추가 확인 필요"는 여기 없다 — 그건 등급이 아니라 분석 상태라서
 * [RiskAssessment.Unverified]로 따로 모델링한다. 등급을 nullable로 두거나
 * UNKNOWN 값을 섞으면 "모름"이 "낮음"으로 흘러가는 경로가 생긴다.
 */
enum class RiskLevel(
    /**
     * 사용자에게 보여줄 한 단어. 색상만으로 위험도를 구분하지 않는다는
     * 접근성 원칙 때문에 등급 자체가 표시 어휘를 가진다.
     */
    val badgeText: String
) {
    /** 광고임이 명확하고 광고주·연결 주소가 일치하며 위험 신호가 없음 */
    LOW("광고"),

    /** 광고·콘텐츠 구분 곤란, 과도한 할인, 낯선 도메인, 반복 리다이렉트 등 의심 신호 */
    MEDIUM("주의"),

    /** 알려진 악성 도메인, 브랜드-주소 불일치, 외부 APK, 개인정보·결제 요구 */
    HIGH("위험")
}
